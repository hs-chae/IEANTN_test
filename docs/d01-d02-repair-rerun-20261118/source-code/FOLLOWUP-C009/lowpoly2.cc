#include <cstdint>
#include <cstdio>
#include <cassert>
#include <vector>
#include <algorithm>
using u64=uint64_t;
using u128=__uint128_t;
using i128=__int128_t;
constexpr u64 D=1ull<<56, EL=16384;
u64 logs[256]; u64 log2d;
u64 lgseries(u64 z,unsigned n){
    u64 z2=(u128)z*z/D, w=z, s=0;
    for(unsigned j=0;j<n;++j){s+=w/(2*j+1);w=(u128)w*z2/D;}
    return 2*s;
}
void init(){
    log2d=lgseries(D/3,32);
    for(unsigned j=0;j<256;++j)logs[j]=lgseries((u128)D*j/(512+j),32);
}
u64 bit(u64 n){return 63-__builtin_clzll(n);}
// floor lower log of n * 2^(-scale); callers have 0<=k<=32.
u64 logd(u64 n, int scale=0){
    int b=bit(n), k=b-scale;
    assert(k>=0 && k<=32);
    u64 y=(b<=56)?(n<<(56-b)):(n>>(b-56));
    u64 i=(y-D)>>(56-8), t=D+(i<<(56-8));
    return k*log2d+logs[i]+lgseries((u128)(y-t)*D/(y+t),4);
}
struct J{u64 lo,hi;};
J corr(u64 p){
    u64 pow=p*p, l=0,h=0;
    unsigned m=2;
    while(pow<=D){
        auto q=D/(pow*m);
        l+=q; h+=q+1;
        if(pow>D/p)break;
        pow*=p; ++m;
    }
    return {l,h+2};
}
u64 N=4000000000, N0=10000000;
std::vector<bool> comp;
u64 gdlo,gdhi,mdlo,mdhi,bdlo,bdhi;
u64 h0=0,h1=0,s0=0,s1=0,q0=0,q1=0;
struct Trial{int early, h,p,s; unsigned last[3]={0,0,0}, next[3]={0,0,0};};
Trial trials[]={{1000,375,375,375},{1000,378,378,378},{1000,380,380,380},{1000,381,381,381},{1000,382,382,382},{1000,383,383,383},{1000,385,385,385},{1000,390,390,390}};
void check(unsigned n,u64 logn){
    u64 L=logn+EL;
    u64 ell0=logd(logn,56), ell1=logd(L,56)+EL;
    // up2/up3 are upper dyadic bounds for L^2 and L^3.
    u128 up2=((u128)L*L+D-1)/D, up3=(up2*L+D-1)/D;
    u64 dh=std::max((i128)h1-(mdlo+ell0),(i128)(mdhi+ell1)-h0);
    u64 dp=std::max((i128)q1-(gdlo+ell0),(i128)(gdhi+ell1)-q0);
    u64 ds=std::max((i128)s1-logn+bdhi,(i128)L-bdlo-s0);
    if(n==2278381 || n==2278382 || n==2278383 || n==912559 || n==912560 || n==3451993 || n==3451793){
        printf("witness %u: ",n);
        for(u64 z:{logn,L,ell0,ell1,h0,h1,q0,q1,s0,s1})printf("%llu ",(unsigned long long)z);
        puts("");
    }
    for(auto &t:trials) if(n>=unsigned(t.early)){
        bool flag[] = {dh>(u128)t.h*D*D/(10000*up3),
                       dp>(u128)t.p*D*D/(10000*up3+t.p*(u128)D),
                       ds>(u128)t.s*D*D/(10000*up2)};
        for(unsigned j=0;j<3;++j)
            if(flag[j]){t.last[j]=n;t.next[j]=0;}
            else if(t.next[j]==0 && n>t.last[j])t.next[j]=n;
    }
}
int main(){
    init();comp.resize(N+1);
    for(u64 p=2;p*p<=N;++p)if(!comp[p])
        for(u64 j=p*p;j<=N;j+=p)comp[j]=true;
    u128 H0=0,H1=0; u64 C0=0,C1=0,B0=0,B1=0;
    for(u64 n=1;n<=N0;++n){H0+=((u128)D<<28)/n;H1+=((u128)D<<28)/n+1;}
    gdlo=(H0>>28)-(logd(N0)+EL)-(D/(2*N0)+1);
    gdhi=(H1>>28)+1-logd(N0)-D/(2*N0)+D/(6*N0*N0)+1;
    for(u64 p=2;p<=N0;++p)if(!comp[p]){
        J c=corr(p); C0+=c.lo; C1+=c.hi;
        u64 a=logd(p), div=p*(p-1);
        B0+=a/div; B1+=(a+EL)/div+1;
    }
    // Tail intervals generated by mcert.py constants() from Dusart 4.2.
    mdlo=gdlo-C1-211651128;mdhi=gdhi-C0-210596567;
    bdlo=gdlo+B0+7189117479; bdhi=gdhi+B1+7222404211;
    printf("dyadic scale %llu\n",(unsigned long long)D);
    for(u64 v:{gdlo,gdhi,mdlo,mdhi,bdlo,bdhi})printf("%llu ",(unsigned long long)v);
    puts("");
    for(unsigned p=2;p<=N;++p){
        if(comp[p] && p!=1000 && p!=N && !(p>1000 && p<=20000000 && p%10000==0) && p!=2278381 && p!=912559 && p!=2278382 && p!=2278383 && p!=912560)continue;
        u64 lp=logd(p);
        if(p>=1000)check(p,lp);
        if(!comp[p]){
            u64 h=D/p;
            h0+=h;h1+=h+1;
            s0+=lp/p;s1+=(lp+EL)/p+1;
            J c=corr(p);
            q0+=h+c.lo;q1+=h+1+c.hi;
        }
        if(p>=1000 && !comp[p])check(p,lp);
    }
    for(auto t:trials){
        assert(t.next[0] && t.next[1] && t.next[2]);
        printf("%d/10000: joins %u %u %u; flags %u %u %u\n",t.h,t.next[0],t.next[1],t.next[2],t.last[0],t.last[1],t.last[2]);
    }
}
