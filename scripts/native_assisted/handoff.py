#!/usr/bin/env python3
"""Write docs/program-verification/PV_APPLICATION_HANDOFF.json: the program-verified applications
as dependency chains, with each link's evidence read from pv-evidence/ and formalization.yaml.

    python scripts/native_assisted/handoff.py

Nothing is typed in by hand except the chain structure (which conclusion feeds which) and the
role of each link. Statuses, native-fact counts, hashes and official kinds come from the files.
"""
from __future__ import annotations

import json
import pathlib
import subprocess

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
EV = ROOT / "pv-evidence"

CHAINS = {
    "ramanujan-from-e401": {
        "statement": "Ramanujan's inequality pi(x)^2 < (e x / log x) pi(x/e) for every x > exp 401, "
                     "conditional on the QRH-derived pi expansion",
        "links": [
            ("DudekPlattNumerics.v5.pi_two_sided_qrh", "analytic premise (node import)"),
            ("RamanujanNumerics.v3.epsilon_budget", "numerical provider (generated by pv_update.py)"),
            ("RamanujanGap.v3.ramanujan", "consumer"),
        ],
        "replay": {"theorem": "RamanujanGap.v3.ramanujan_from_pi",
                   "project": "Solutions/RamanujanGap.v3",
                   "axioms": "propext, Classical.choice, Quot.sound + 1 native fact "
                             "(RamanujanNumerics.v3.Provider.certificate)"},
    },
    "pilot-A-to-Bprime": {
        "statement": "(1 + 13.6862/log x) x^2/log^6 x < gap(x) for every x > exp 9401, from "
                     "QRHCH2.v5.psi_refined_bound (controlled replay, not a node)",
        "links": [
            ("@pv.PVPilot.Updated.gap_exceeds_leading", "two executed stages joined by a data link"),
        ],
        "data_link": "PVPilot.Updated.link : B'.M = 120 + A's certified bound (kernel-checked rational equality)",
    },
}


def attestation(key: str) -> dict | None:
    p = EV / f"{key}.native-assisted.local.json"
    return json.loads(p.read_text()) if p.is_file() else None


def official(key: str) -> dict | None:
    if key.startswith("@"):
        return None
    import yaml
    node, cid = key.rsplit(".", 1)
    fam, ver = node.rsplit(".", 1)
    y = ROOT / "IEANTN" / "Nodes" / fam / ver / "formalization.yaml"
    meta = yaml.safe_load(y.read_text())
    c = next(c for c in meta["conclusions"] if c["id"] == cid)
    j = next(j for j in c["justifications"] if j["id"] == c["designated"])
    return {"designated_kind": j["kind"], "verification_method": j.get("verification_method"),
            "imports": [f"{i['node']}.{i['conclusion']}" for i in c.get("imports") or []],
            "receipt": (ROOT / "receipts" / f"{key}.json").is_file()}


def link(key: str, role: str) -> dict:
    a = attestation(key)
    out = {"conclusion": key, "role": role, "official": official(key)}
    if a is None:
        out["local_gate"] = "not-run"
        return out
    checks = a.get("method_checks") or {}
    out["local_gate"] = {"status": a["status"], "evidence_method": a["evidence_method"],
                         "native_facts": (a.get("axioms") or {}).get("native_fact_count"),
                         "native_fact_owners": sorted({n["decl"] for n in (a.get("axioms") or {}).get("native_facts", [])}),
                         "checked_at": (a.get("run") or {}).get("checked_at_utc"),
                         "repository_commit": (a.get("pins") or {}).get("repository_commit"),
                         "attestation": f"pv-evidence/{key}.native-assisted.local.json"}
    srcs = (checks.get("S_source_identity") or {}).get("sources") or []
    if srcs:
        out["program"] = {"backend": "restricted C, IEEE binary64 round-to-nearest (PVCore.Program)",
                          "sources": [{"path": s["path"], "sha256": s["sha256"]} for s in srcs],
                          "proved_by": (checks.get("C_generic_correctness") or {}).get("theorems")}
    return out


def main() -> int:
    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True,
                            text=True).stdout.strip()
    doc = {"schema": "agentB.pv-application-handoff/1 (local sidecar; not an official IEANTN schema)",
           "notice": "Local research record. Not an IEANTN verification receipt.",
           "generated_at_commit": commit,
           "trust_boundary": json.loads((HERE / "semantics.json").read_text())["trust_boundary"],
           "applications": {}}
    for name, ch in CHAINS.items():
        doc["applications"][name] = {k: v for k, v in ch.items() if k != "links"}
        doc["applications"][name]["links"] = [link(k, r) for k, r in ch["links"]]
    out = ROOT / "docs" / "program-verification" / "PV_APPLICATION_HANDOFF.json"
    out.write_text(json.dumps(doc, indent=1) + "\n")
    print("wrote", out.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
