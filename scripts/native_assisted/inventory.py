#!/usr/bin/env python3
"""Regenerate docs/program-verification/PROGRAM_VERIFICATION_INVENTORY.md from attestations + metadata.

    python scripts/native_assisted/inventory.py

Every row comes from pv-evidence/*.native-assisted.local.json, which the checker writes from
actual elaboration, and from formalization.yaml / receipts/. Nothing is typed in by hand except the
per-family prose in HEAD.
"""
from __future__ import annotations

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
EVIDENCE = ROOT / "pv-evidence"
OUT = ROOT / "docs" / "program-verification" / "PROGRAM_VERIFICATION_INVENTORY.md"
ENDPOINTS = json.loads((HERE / "endpoints.json").read_text())["endpoints"]

HEAD = """# Program-verification inventory (generated)

Generated by `scripts/native_assisted/inventory.py` from the local attestations in `pv-evidence/`
and from the node metadata. **The attestations are local research reports, not receipts.** The
classification axes are defined in [NATIVE_ASSISTED_DESIGN.md](NATIVE_ASSISTED_DESIGN.md).

The "old" columns are what the metadata said before this work: the official kind, and the
justification id or note claims such as "source-verified". The "new" columns are what the gate
found in the actual proof closure. The official kind is never changed by this work.
"""

ORDER = ["PoC1", "Table4", "Ramanujan", "Pilot"]
FAMILY_TITLE = {"PoC1": "PoC 1: FKS2 scalar ν correction", "Table4": "FKS2 Table 4 θ→π transport",
                "Ramanujan": "Forward Ramanujan quantitative gap",
                "Pilot": "A→B calibration pilot (not a node)"}


def fmt_hyps(r):
    hs = r.get("remaining_hypotheses") or []
    return "; ".join(h["type"] for h in hs) if hs else "none"


def row(key, r):
    off = r.get("official") or {}
    ax = r.get("axioms") or {}
    m = r.get("method_checks") or {}
    checks = "".join("✓" if (m.get(k) or {}).get("ok") else "✗" for k in
                     ("S_source_identity", "A_source_association", "E_execution_witness",
                      "C_generic_correctness", "M_mathematical_endpoint"))
    srcs = ", ".join(f"`{s['path']}` (`{(s['sha256'] or '')[:12]}`)"
                     for s in (m.get("S_source_identity") or {}).get("sources", [])) or "none"
    natives = ", ".join(f"`{n['decl'].split('.')[-1]}`" for n in ax.get("native_facts", []))
    return (f"| `{key}` | `{r.get('endpoint')}` | {off.get('designated_kind', 'n/a (not a node)')}"
            f" / `{off.get('designated_id', '-')}` | {r.get('evidence_method')} ({checks}) | "
            f"**{r.get('status')}** | {', '.join(ax.get('standard', []))} | "
            f"{ax.get('native_fact_count', '-')}: {natives or '-'} | "
            f"{len(ax.get('rejected') or [])} | {srcs} | {fmt_hyps(r)} | "
            f"{off.get('official_comparator_receipt', 'n/a')} |")


def main():
    reports = {}
    for p in sorted(EVIDENCE.glob("*.native-assisted.local.json")):
        r = json.loads(p.read_text())
        reports[r["conclusion"]] = r
    lines = [HEAD]
    lines.append("Columns:\n\n- **official kind / id**: the designated justification, unchanged;\n"
                 "- **evidence method (S A E C M)**: the method found in the proof, with the five "
                 "checks;\n- **gate**: the native-assisted verdict, freshly rerun;\n"
                 "- **std / native / rejected**: the axiom ledger;\n- **sources**: executed C "
                 "files with SHA256 prefixes;\n- **hypotheses**: explicit premises of the "
                 "endpoint;\n- **receipt**: the official Comparator receipt status.\n")
    for fam in ORDER:
        keys = [k for k, c in ENDPOINTS.items() if c.get("family") == fam]
        if not keys:
            continue
        lines.append(f"\n## {FAMILY_TITLE[fam]}\n")
        lines.append("| key | endpoint | official kind / id | evidence method (S A E C M) | gate | "
                     "std axioms | native facts | rejected | sources | hypotheses | receipt |")
        lines.append("|---|---|---|---|---|---|---|---|---|---|---|")
        for k in keys:
            r = reports.get(k)
            if r is None:
                lines.append(f"| `{k}` | `{ENDPOINTS[k]['endpoint']}` | | | **not-run** | | | | | | |")
            else:
                lines.append(row(k, r))
        for k in keys:
            r = reports.get(k)
            if r and r.get("status") != "passed":
                lines.append(f"\n- `{k}` {r['status']}: " + "; ".join(r.get("reasons") or r.get("blockers") or []))
    lines.append("\n## Proof locations (from the attestations)\n")
    for k, r in reports.items():
        mods = [m for m in r.get("project_modules", []) if m.get("source")]
        m = r.get("method_checks") or {}
        lines.append(f"- `{k}` → `{r.get('endpoint')}`: association "
                     f"{', '.join('`'+t+'`' for t in (m.get('A_source_association') or {}).get('theorems', [])[:3]) or '-'}; "
                     f"execution {', '.join('`'+t+'`' for t in (m.get('E_execution_witness') or {}).get('theorems', [])[:3]) or '-'}; "
                     f"correctness {', '.join('`'+t+'`' for t in (m.get('C_generic_correctness') or {}).get('theorems', [])[:3]) or '-'}; "
                     f"{len(mods)} project modules hashed; closure fingerprint `{(r.get('proof_closure_fingerprint') or '')[:16]}`.")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(reports)} attestations)")


if __name__ == "__main__":
    main()
