#!/usr/bin/env python3
"""Local `native-assisted` gate for IEANTN program-verification endpoints (NOT an official check).

    python scripts/native_assisted/native_assisted_check.py check <Conclusion.id> [--no-build]
    python scripts/native_assisted/native_assisted_check.py check-all [--no-build]
    python scripts/native_assisted/native_assisted_check.py evaluate <extract.json> [--challenge <c.json>] ...

The gate admits a proof whose transitive axiom closure contains only:
* `propext`, `Classical.choice` and `Quot.sound`; and
* finite native-evaluation facts whose provenance can be audited. Such a fact must be an axiom
  `<D>._native.native_decide.ax_*` of type `@Eq Bool e true`, generated by Lean's `nativeEqTrue`.
  `D` must be a project theorem in the same module. The declaration range must point at the
  literal `native_decide` tactic token in that module's source file, which is hashed. No reachable
  project constant may carry `implemented_by` or `extern`.
Everything else fails closed. That includes `sorryAx`, custom axioms, other native mechanisms,
unsafe constants, unresolvable or ambiguous provenance, a challenge-type mismatch, and a failed
build.

Separately, the *evidence method* `lean-verified-program` is recorded only if the proof closure
contains all of the following:
* (S) a string literal equal byte-for-byte to the configured C source file;
* (A) a proved source-association fact about that literal;
* (E) a proved execution witness for that literal under a reviewed execution relation;
* (C) a reviewed generic correctness theorem;
* (M) an endpoint that is a mathematical statement, not a statement about the program.

Output is a local research attestation in pv-evidence/. It is never a receipt, never written to
receipts/, and never sets `lean-comparator`.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import hashlib
import json
import os
import pathlib
import re
import subprocess
import sys
import time

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
EXTRACT = HERE / "Extract.lean"
ENDPOINTS = HERE / "endpoints.json"
SEMANTICS = HERE / "semantics.json"
EVIDENCE = ROOT / "pv-evidence"
RECEIPTS = ROOT / "receipts"

STANDARD_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}
OTHER_NATIVE_MECHANISMS = {"Lean.ofReduceBool", "Lean.ofReduceNat", "Lean.trustCompiler"}
NOTICE = ("LOCAL RESEARCH ATTESTATION (native-assisted gate). Not an IEANTN verification receipt, "
          "not issued by Comparator, not an official justification. Native evaluation extends the "
          "trusted base; restricted-C/RN64 semantics, compiler, runtime and hardware are trusted.")


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def sha256_file(p: pathlib.Path) -> str:
    return sha256_bytes(p.read_bytes())


def load_json(p: pathlib.Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


# ---------------------------------------------------------------- source resolution

def _lib_src_dirs(pkg: pathlib.Path) -> list[str]:
    """srcDir values declared in a package's lakefile.toml (default '.')."""
    dirs = ["."]
    lf = pkg / "lakefile.toml"
    if lf.is_file():
        for m in re.finditer(r'^\s*srcDir\s*=\s*"([^"]+)"', lf.read_text(encoding="utf-8"), re.M):
            dirs.append(m.group(1))
    return dirs


def resolve_source(module: str, olean: str) -> pathlib.Path | None:
    """Map a module and the olean it was loaded from to exactly one source file, else None."""
    marker = "/.lake/build/lib/lean/"
    if marker not in olean:
        return None
    pkg = pathlib.Path(olean.split(marker)[0])
    rel = pathlib.Path(*module.split(".")).with_suffix(".lean")
    hits = [pkg / d / rel for d in _lib_src_dirs(pkg) if (pkg / d / rel).is_file()]
    hits = list(dict.fromkeys(p.resolve() for p in hits))
    return hits[0] if len(hits) == 1 else None


def text_at(path: pathlib.Path, rng: dict) -> str | None:
    """Text of a Lean declaration range (1-based lines, 0-based UTF-8 codepoint columns)."""
    try:
        lines = path.read_text(encoding="utf-8").split("\n")
        sl, sc, el, ec = rng["start_line"], rng["start_col"], rng["end_line"], rng["end_col"]
        if sl == el:
            return lines[sl - 1][sc:ec]
        parts = [lines[sl - 1][sc:]] + lines[sl:el - 1] + [lines[el - 1][:ec]]
        return "\n".join(parts)
    except Exception:  # noqa: BLE001 - any failure means provenance is not auditable
        return None


# ---------------------------------------------------------------- policy

def evaluate(extract: dict, challenge: dict | None, cfg: dict, sem: dict,
             reviewed_impl: set[str] | None = None) -> dict:
    """Pure policy evaluation of one extract. Deterministic; no I/O except reading sources."""
    reviewed_impl = reviewed_impl or set(sem.get("reviewed_project_implementations", []))
    reasons: list[str] = []
    blockers: list[str] = []
    mod_olean = {m["module"]: m["olean"] for m in extract.get("project_modules", [])}
    src_cache: dict[str, pathlib.Path | None] = {}

    def src_of(module: str) -> pathlib.Path | None:
        if module not in src_cache:
            src_cache[module] = resolve_source(module, mod_olean.get(module, ""))
        return src_cache[module]

    standard, natives, rejected = [], [], []
    for ax in extract.get("axioms", []):
        name, module = ax["name"], ax["module"]
        nat = ax.get("native")
        if name in STANDARD_AXIOMS and module.startswith("Init"):
            standard.append(name)
            continue
        if name == "sorryAx":
            rejected.append({"name": name, "why": "sorryAx (incomplete proof)"})
            continue
        if name in OTHER_NATIVE_MECHANISMS:
            blockers.append(f"{name}: a native mechanism this gate has not reviewed")
            rejected.append({"name": name, "why": "unreviewed native mechanism"})
            continue
        if nat is None:
            rejected.append({"name": name, "module": module, "why": "axiom not generated by an "
                             "audited native_decide call (custom or unknown axiom)"})
            continue
        why = []
        if nat.get("tactic") not in sem.get("allowed_native_tactics", ["native_decide"]):
            why.append(f"native tactic {nat.get('tactic')!r} not allowed")
        if any(module == r or module.startswith(r + ".") for r in sem["library_roots"]):
            why.append("native fact declared in a library module")
        if not nat.get("decl_exists") or not nat.get("decl_is_theorem"):
            why.append("owning declaration missing or not a theorem")
        if nat.get("decl_module") != module:
            why.append("axiom and owning theorem are in different modules")
        if not nat.get("eq_true_shape") or nat.get("has_fvar_or_mvar"):
            why.append("type is not the closed `@Eq Bool e true` shape")
        src = src_of(module)
        rng = ax.get("range")
        token = text_at(src, rng) if (src and rng) else None
        if src is None:
            why.append("source file not uniquely resolvable from the loaded olean")
        elif token is None or token.strip() != "native_decide":
            why.append(f"declaration range does not point at a `native_decide` token (found {token!r})")
        impls = nat.get("implementations") or []
        proj_impl = sorted({i["name"] for i in impls if not i.get("library")} - reviewed_impl)
        if proj_impl:
            why.append("native evaluation reaches unreviewed project implemented_by/extern: "
                       + ", ".join(proj_impl))
        lib_impl = sorted({i["name"] for i in impls if i.get("library")})
        rec = {"name": name, "decl": nat.get("decl"), "module": module,
               "source_file": str(src.relative_to(ROOT)) if src and src.is_relative_to(ROOT) else (str(src) if src else None),
               "source_sha256": sha256_file(src) if src else None, "range": rng, "token": token,
               "decided_proposition": nat.get("decided_prop_pp"),
               "trusted_library_implementations": len(lib_impl),
               "trusted_library_implementation_names": lib_impl}
        if why:
            rec["why"] = "; ".join(why)
            rejected.append(rec)
        else:
            natives.append(rec)

    for c in extract.get("project_constants", []):
        if c.get("unsafe"):
            rejected.append({"name": c["name"], "why": "unsafe declaration in proof closure"})
        if (c.get("implemented_by") or c.get("extern")) and c["name"] not in reviewed_impl:
            rejected.append({"name": c["name"], "why": "project implemented_by/extern in closure"})

    missing_std = sorted(STANDARD_AXIOMS - set(standard))
    challenge_match = None
    if challenge is not None:
        # alpha-equivalence: binder names are not part of a theorem's statement
        key = "endpoint_type_canonical" if "endpoint_type_canonical" in extract else "endpoint_type_all"
        # A second route to an existing conclusion names its own theorem; the generated challenge
        # keeps the node's name, given as `challenge_endpoint`.
        challenge_match = (challenge.get("endpoint") == cfg.get("challenge_endpoint", extract.get("endpoint")) and
                           challenge.get(key) is not None and challenge.get(key) == extract.get(key))
        if not challenge_match:
            reasons.append("solution theorem type differs from the generated challenge")
        if extract.get("endpoint_module", "").endswith(".Challenge"):
            reasons.append("endpoint resolved to the challenge itself, not a solution")
    elif cfg.get("challenge_decl"):
        blockers.append("challenge type not extracted")

    if extract.get("endpoint_kind") != "theorem":
        reasons.append(f"endpoint is a {extract.get('endpoint_kind')}, not a theorem")
    if rejected:
        reasons += [f"{r['name']}: {r['why']}" for r in rejected]

    method = method_checks(extract, cfg, sem)
    status = "blocked" if blockers else ("failed" if reasons else "passed")
    project_mods = sorted(mod_olean)
    fp_lines = [extract.get("endpoint_type_all", "")]
    for m in project_mods:
        s = src_of(m)
        fp_lines.append(f"{m}\t{sha256_file(s) if s else 'UNRESOLVED'}")
    return {
        "status": status, "reasons": reasons, "blockers": blockers,
        "challenge_type_match": challenge_match,
        "axioms": {"standard": sorted(standard), "standard_missing": missing_std,
                   "native_facts": sorted(natives, key=lambda r: r["name"]),
                   "native_fact_count": len(natives), "rejected": rejected},
        "method": method,
        "proof_closure_fingerprint": sha256_bytes("\n".join(fp_lines).encode()),
        "project_modules": [{"module": m, "source": (str(src_of(m).relative_to(ROOT))
                              if src_of(m) and src_of(m).is_relative_to(ROOT) else None),
                             "sha256": sha256_file(src_of(m)) if src_of(m) else None}
                            for m in project_mods],
    }


def method_checks(extract: dict, cfg: dict, sem: dict) -> dict:
    consts = {c["name"]: c for c in extract.get("project_constants", [])}
    sources = []
    lit_by_hash = {}
    for lit in extract.get("string_literals", []):
        try:
            h = sha256_bytes(pathlib.Path(lit["file"]).read_bytes())
        except OSError:
            continue
        lit_by_hash.setdefault(h, []).append(lit["name"])
    for rel in cfg.get("sources", []):
        p = ROOT / rel
        h = sha256_file(p) if p.is_file() else None
        sources.append({"path": rel, "sha256": h, "embedded_by": lit_by_hash.get(h, []) if h else []})
    literals = sorted({n for s in sources for n in s["embedded_by"]})
    assoc_fns = set(sem["association"])
    exec_rels = set(sem["execution"])
    correct = set(sem["correctness"])

    def reach(names, depth: int = 6) -> set:
        """Names plus everything their *definitions* mention, transitively (project only)."""
        seen, frontier = set(names), set(names)
        for _ in range(depth):
            nxt = set()
            for n in frontier:
                c = consts.get(n)
                if c and c.get("kind") == "def":
                    nxt |= set(c.get("value_mentions") or [])
            frontier = nxt - seen
            seen |= frontier
            if not frontier:
                break
        return seen

    def theorems_mentioning(*need_any_groups):
        """Theorems (or native-fact owners) whose statement reaches every group via definitions."""
        out = []
        for c in consts.values():
            if c.get("kind") not in ("theorem", "axiom"):
                continue
            ms = reach(c.get("type_mentions") or [])
            if all(ms & g for g in need_any_groups):
                out.append(c["name"])
        return sorted(out)

    lit_set = set(literals)
    s_ok = bool(literals) and all(s["embedded_by"] for s in sources)
    a_thms = theorems_mentioning(lit_set, assoc_fns) if lit_set else []
    e_thms = theorems_mentioning(lit_set, exec_rels) if lit_set else []
    c_hits = sorted(correct & set(consts))
    etype = extract.get("endpoint_type_all", "")
    program_level = sorted(n for n in (lit_set | exec_rels | assoc_fns) if n and n in etype)
    m_ok = not program_level
    verified = bool(s_ok and a_thms and e_thms and c_hits and m_ok)
    return {
        "claimed": cfg.get("method_claim", "lean-verified-program"),
        "result": "lean-verified-program" if verified else "not-program-verified",
        "S_source_identity": {"ok": s_ok, "sources": sources, "embedded_literals": literals},
        "A_source_association": {"ok": bool(a_thms), "theorems": a_thms},
        "E_execution_witness": {"ok": bool(e_thms), "theorems": e_thms},
        "C_generic_correctness": {"ok": bool(c_hits), "theorems": c_hits},
        "M_mathematical_endpoint": {"ok": m_ok, "program_level_constants_in_statement": program_level},
    }


# ---------------------------------------------------------------- running Lean

def run(cmd: list[str], cwd: pathlib.Path, timeout: int) -> tuple[int, str, float]:
    t0 = time.time()
    try:
        p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout)
        return p.returncode, (p.stdout + p.stderr), time.time() - t0
    except subprocess.TimeoutExpired:
        return 124, "timeout", time.time() - t0
    except FileNotFoundError as e:
        return 127, str(e), time.time() - t0


def extract(project: pathlib.Path, root_module: str, endpoint: str, out: pathlib.Path,
            timeout: int = 1800) -> tuple[dict | None, dict]:
    libdir = project / ".lake" / "build" / "lib" / "lean"
    cmd = ["lake", "env", "lean", "--run", str(EXTRACT), root_module, endpoint, str(out), str(libdir)]
    rc, log, secs = run(cmd, project, timeout)
    meta = {"command": " ".join(cmd), "cwd": str(project.relative_to(ROOT)) if project.is_relative_to(ROOT) else str(project),
            "rc": rc, "seconds": round(secs, 1), "log_tail": log[-600:]}
    olean_note = pathlib.Path(str(out) + ".root_olean")
    if olean_note.is_file():
        meta["root_olean"] = olean_note.read_text().strip()
    if rc != 0 or not out.is_file():
        return None, meta
    return load_json(out), meta


def pins(project: pathlib.Path) -> dict:
    out = {"lean_toolchain": (project / "lean-toolchain").read_text().strip()
           if (project / "lean-toolchain").is_file() else None}
    man = ROOT / "lake-manifest.json"
    if man.is_file():
        for p in load_json(man).get("packages", []):
            if p.get("name") == "mathlib":
                out["mathlib"] = p.get("rev")
    rc, log, _ = run(["git", "rev-parse", "HEAD"], ROOT, 30)
    out["repository_commit"] = log.strip() if rc == 0 else None
    rc, log, _ = run(["git", "status", "--porcelain", "--untracked-files=no"], ROOT, 30)
    out["working_tree_clean"] = (rc == 0 and log.strip() == "")
    return out


def official_status(conclusion: str) -> dict:
    import yaml  # the repository's own dependency
    node, cid = conclusion.rsplit(".", 1)
    fam, ver = node.rsplit(".", 1)
    meta = yaml.safe_load((ROOT / "IEANTN" / "Nodes" / fam / ver / "formalization.yaml").read_text())
    conc = next(c for c in meta["conclusions"] if c["id"] == cid)
    des = conc.get("designated")
    j = next((j for j in conc.get("justifications", []) if j.get("id") == des), {})
    receipt = RECEIPTS / f"{conclusion}.json"
    return {"designated_id": des, "designated_kind": j.get("kind"),
            "graph_imports": [f"{i['node']}.{i['conclusion']}" for i in conc.get("imports") or []],
            "official_comparator_receipt": "present" if receipt.is_file() else "absent"}


def check(conclusion: str, build: bool = True, out_dir: pathlib.Path = EVIDENCE) -> dict:
    cfgs = load_json(ENDPOINTS)["endpoints"]
    sem = load_json(SEMANTICS)
    cfg = cfgs[conclusion]
    project = ROOT / cfg["project"]
    work = out_dir / ".work" / conclusion
    work.mkdir(parents=True, exist_ok=True)
    report: dict = {"notice": NOTICE, "gate": "native-assisted", "conclusion": conclusion,
                    "endpoint": cfg["endpoint"], "project": cfg["project"]}
    run_meta: dict = {"checked_at_utc": _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds"),
                      "checker_sha256": sha256_file(pathlib.Path(__file__)),
                      "extractor_sha256": sha256_file(EXTRACT)}
    report["pins"] = pins(project)
    if build:
        rc, log, secs = run(["lake", "build", cfg["root_module"]], project, 7200)
        run_meta["build"] = {"command": f"lake build {cfg['root_module']}", "rc": rc,
                             "seconds": round(secs, 1), "replayed_or_built_tail": log[-400:]}
        if rc != 0:
            env_markers = ("package directory not found", "could not fetch", "failed to clone",
                           "toolchain", "No space left", "timeout", "Killed")
            if rc in (124, 127, 137, 143, -9, -15) or any(m in log for m in env_markers):
                report.update(status="blocked", reasons=[], blockers=[
                    f"build environment problem (rc={rc}); not a verdict on the proof"], run=run_meta)
            else:
                report.update(status="failed", reasons=[f"lake build failed (rc={rc})"], run=run_meta)
            return report
    ex, ex_meta = extract(project, cfg["root_module"], cfg["endpoint"], work / "solution.json")
    run_meta["extract_solution"] = ex_meta
    ch = None
    if cfg.get("challenge_module"):
        ch, ch_meta = extract(ROOT, cfg["challenge_module"], cfg.get("challenge_endpoint", cfg["endpoint"]),
                              work / "challenge.json")
        run_meta["extract_challenge"] = ch_meta
    if ex is None or (cfg.get("challenge_module") and ch is None):
        report.update(status="blocked", reasons=["extraction did not run; see run.extract_*"],
                      run=run_meta)
        return report
    ev = evaluate(ex, ch, cfg, sem)
    report.update({
        "status": ev["status"], "reasons": ev["reasons"], "blockers": ev["blockers"],
        "statement": ex.get("endpoint_type_pp"),
        "statement_type_all_sha256": sha256_bytes(ex.get("endpoint_type_all", "").encode()),
        "statement_type_canonical_sha256": sha256_bytes(ex.get("endpoint_type_canonical", "").encode()),
        "remaining_hypotheses": ex.get("endpoint_hypotheses", []),
        "challenge_type_match": ev["challenge_type_match"],
        "axioms": ev["axioms"], "evidence_method": ev["method"]["result"],
        "method_checks": ev["method"], "proof_closure_fingerprint": ev["proof_closure_fingerprint"],
        "project_modules": ev["project_modules"], "closure_size": ex.get("closure_size"),
        "lean_version": ex.get("lean_version"), "lean_githash": ex.get("lean_githash"),
        "official": (official_status(conclusion) if cfg.get("is_node_conclusion", True) else
                     official_status(cfg["replays"]) if cfg.get("replays") else None),
        "replays": cfg.get("replays"),
        "trust_boundary": sem["trust_boundary"],
        "promotion_rule": sem["promotion_rule"],
    })
    report["run"] = run_meta
    return report


def write_report(report: dict, out_dir: pathlib.Path = EVIDENCE) -> pathlib.Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{report['conclusion']}.native-assisted.local.json"
    path.write_text(json.dumps(report, indent=1, sort_keys=True, ensure_ascii=False) + "\n")
    return path


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    c1 = sub.add_parser("check"); c1.add_argument("conclusion"); c1.add_argument("--no-build", action="store_true")
    c2 = sub.add_parser("check-all"); c2.add_argument("--no-build", action="store_true")
    c3 = sub.add_parser("evaluate"); c3.add_argument("extract"); c3.add_argument("--challenge")
    c3.add_argument("--sources", nargs="*", default=[])
    a = ap.parse_args(argv)
    if a.cmd == "evaluate":
        ex = load_json(pathlib.Path(a.extract))
        ch = load_json(pathlib.Path(a.challenge)) if a.challenge else None
        print(json.dumps(evaluate(ex, ch, {"sources": a.sources}, load_json(SEMANTICS)), indent=1))
        return 0
    names = [a.conclusion] if a.cmd == "check" else list(load_json(ENDPOINTS)["endpoints"])
    worst = 0
    for n in names:
        r = check(n, build=not a.no_build)
        p = write_report(r)
        print(f"{n}: {r['status']} method={r.get('evidence_method')} "
              f"native={r.get('axioms', {}).get('native_fact_count')} -> {p.relative_to(ROOT)}")
        worst = max(worst, {"passed": 0, "failed": 1, "blocked": 2}[r["status"]])
    return worst


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
