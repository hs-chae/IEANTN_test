#!/usr/bin/env python3
"""Preview/apply only the 256 byte-regenerated unit-baseline scratch files."""
from pathlib import Path
import argparse
import hashlib
import json
import os
import stat
import time


def need(value, message):
    if not value:
        raise ValueError(message)


def sha(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def read(path):
    def pairs(items):
        result = {}
        for key, value in items:
            need(key not in result, "duplicate JSON key")
            result[key] = value
        return result
    return json.loads(Path(path).read_text(), object_pairs_hook=pairs,
                      parse_constant=lambda _: (_ for _ in ()).throw(ValueError("nonfinite JSON")))


def atomic(path, value):
    need(not path.exists(), "preserve existing result")
    path.parent.mkdir(parents=True, exist_ok=True)
    pending = path.with_name(path.name + ".tmp")
    need(not pending.exists(), "fresh atomic temporary")
    pending.write_text(json.dumps(value, indent=2) + "\n")
    os.link(pending, path)
    pending.unlink()


def main():
    parser = argparse.ArgumentParser(allow_abbrev=False)
    parser.add_argument("--scratch", type=Path, required=True)
    parser.add_argument("--preview", type=Path, required=True)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--expected-preview-sha")
    parser.add_argument("--result", type=Path)
    args = parser.parse_args()
    need(args.scratch.is_absolute() and args.preview.is_absolute(), "absolute reviewed paths required")
    scratch = args.scratch.resolve()
    need(scratch.name == "ivy-ramanujan-source-pv-20261119" and scratch.is_dir(), "owned scratch root")
    receipt_path = scratch / "unit-regeneration-before-cleanup-v1/RESULT.json"
    regenerated = read(receipt_path)
    need(regenerated["status"] == "PASS_BOTH_FULL_UNIT_BASELINES_BYTE_EXACT_REGENERATION", "completed checked regeneration required")
    rows = regenerated["rows"]
    need(len(rows) == 128 and {(r["end"], r["chunk"]) for r in rows} == {(end, i) for end in [1490000000000, 1620000000000] for i in range(64)}, "both full fixed chunk universes")
    targets = []
    for row in rows:
        end, index = row["end"], row["chunk"]
        expected = [scratch / ("finite-unit-" + str(end)) / (str(index) + ".bin"),
                    scratch / "unit-regeneration-before-cleanup-v1" / str(end) / (str(index) + ".bin")]
        need([Path(row["original_generated_file"]), Path(row["generated_file"])] == expected, "exact experiment-owned targets")
        for target in expected:
            need(target.resolve() == target and not target.is_symlink(), "no linked or external cleanup path")
            meta = target.lstat()
            need(stat.S_ISREG(meta.st_mode) and meta.st_nlink == 1, "single owned regular file required")
            need(meta.st_size == row["byte_length"] and sha(target) == row["sha256"], "every actual cleanup target matches its regenerated bytes")
            targets.append(dict(path=str(target), bytes=meta.st_size, sha256=row["sha256"],
                                inode=meta.st_ino, device=meta.st_dev, mtime_ns=meta.st_mtime_ns))
    need(len({t["path"] for t in targets}) == 256, "exactly 256 distinct regenerable targets")
    plan = dict(status="PREVIEW_ONLY_ALL_TARGETS_BYTE_REGENERATED", scratch=str(scratch),
                regeneration_receipt=str(receipt_path), regeneration_sha256=sha(receipt_path),
                script_sha256=sha(__file__), targets=targets, total_bytes=sum(t["bytes"] for t in targets),
                preservation="Sources, original results/manifests, reproducibility scripts, failed attempts, adaptive certificates, accepted proofs and all active numerical/compilation work are excluded.")
    if not args.apply:
        need(args.expected_preview_sha is None and args.result is None, "preview-only argument contract")
        atomic(args.preview, plan)
        print(json.dumps({"status": plan["status"], "files": len(targets), "bytes": plan["total_bytes"], "preview_sha256": sha(args.preview)}))
        return
    need(args.expected_preview_sha is not None and args.result is not None and args.result.is_absolute(), "reviewed preview digest and absolute fresh result required")
    need(sha(args.preview) == args.expected_preview_sha, "reviewed preview identity")
    need(read(args.preview) == plan, "every target and prerequisite must remain identical to reviewed preview")
    need(not args.result.exists(), "preserve existing cleanup result")
    started = time.monotonic()
    for target in targets:
        file = Path(target["path"])
        meta = file.lstat()
        need((meta.st_ino, meta.st_dev, meta.st_size, meta.st_mtime_ns) ==
             (target["inode"], target["device"], target["bytes"], target["mtime_ns"]), "target changed after complete verification")
        file.unlink()
    need(all(not Path(t["path"]).exists() for t in targets), "actual removal verification")
    result = dict(status="REMOVED_ONLY_256_VERIFIED_REGENERABLE_UNIT_BASELINE_FILES", preview=str(args.preview),
                  preview_sha256=args.expected_preview_sha, removed_files=len(targets), removed_bytes=plan["total_bytes"],
                  elapsed_seconds=time.monotonic() - started, remaining_sources_and_results_preserved=True)
    atomic(args.result, result)
    print(json.dumps(result))


if __name__ == "__main__":
    main()
