#!/usr/bin/env python3
"""Generate the power-form transport programs (untrusted helper).

    python scripts/generate_power.py            # write the configurations below
    python scripts/generate_power.py --check    # recompute and compare with the files on disk

For a θ profile `Eθ ≤ K·t^{-1/8}` on `t ≥ e^300`, `Table4Evolution.PowerTransport.power_ray` gives

    Eπ(x) ≤ (K + K·κ/330 + (330/300)·e^{45/4}·(1.6997e-12 + K·e^{-75/2})) · x^{-1/8},   x ≥ e^330,

with `κ = 600/521` (the closed-form integral bound replaces the cell sum). The program computes this
coefficient: `inputs = [2^k·K, 2^k·K·κ/330]` (upward binary64), `r = sum(inputs, 2)·2^{-k} + anchor`.
The anchor literal bounds the last term with the same exponential enclosures as `Bounds.expUp`.
Nothing here is trusted: Lean decodes the C literals and re-checks every inequality (`powerOK`).
"""
from __future__ import annotations

import pathlib
import sys
from fractions import Fraction as F

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import generate as T  # noqa: E402  (the same exact definitions and frozen literal rounding)

PROJECT = HERE.parent
KAPPA = F(600, 521)

CONFIGS = [
    # network: QRHPropagation.v2.theta_frontier row (300, 0.01310), i.e. Eθ ≤ (0.01310 + 1e-5)·x^{-1/8}
    dict(name="power_network", ns="PowerNetwork", K=F("0.01310") + F(1, 10 ** 5)),
    # Agent A: WinnerDensityA.revers_source_theta300, Eθ ≤ (0.009782 + 1e-12)·x^{-1/8}
    dict(name="power_agentA", ns="PowerAgentA", K=F("0.009782") + F(1, 10 ** 12)),
    # changed-input replay: Agent A's other evaluation, WinnerDensityA.source_theta300 (original inputs)
    dict(name="power_agentA_source", ns="PowerAgentASource", K=F("0.009904") + F(1, 10 ** 12)),
]


def exp_up(y: F) -> F:  # Bounds.expUp for y ≠ 0
    return T.exp_hi(y) ** 4


def build(cfg: dict) -> dict:
    K = cfg["K"]
    terms = [K, K * KAPPA / 330]
    k = 0
    while all(T.G.upward(F(2) ** (k + 1) * t) <= 1 for t in terms):
        k += 1
    xs = [T.G.upward(F(2) ** k * t) for t in terms]
    assert all(x >= T.LOW for x in xs)
    anchor_hi = F(330, 300) * exp_up(F(45, 16)) * (F("1.6997e-12") + K * exp_up(F(-75, 8)))
    anchor = T.G.upward(anchor_hi)
    lits = [T.G.literal(x) for x in xs]
    scale = T.G.literal(F(1, 2 ** k))
    alit = T.G.literal(anchor)
    csrc = T.render_single("fks2_power_transport", lits, scale, [("+", alit)])
    acc = 0.0
    for x in xs:
        acc = acc + float(x)
    est = F(acc) * F(1, 2 ** k) + anchor
    return dict(cfg, k=k, xs=xs, lits=lits, scale=scale, anchor=anchor, alit=alit, csrc=csrc,
                exact=K * (1 + KAPPA / 330) + anchor_hi, estimate=est)


def lean_data(r: dict) -> str:
    lits = ",\n    ".join(f'"{l}"' for l in r["lits"])
    return f"""/-
Copyright (c) 2026 IEANTN contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Agent B (Claude)
-/
import Mathlib.Data.Rat.Defs

/-! Generated by `scripts/generate_power.py` (configuration `{r["name"]}`); do not edit. Lean re-checks
every literal (`PowerTransport.powerOK`); this file only records the data. -/

namespace Table4Evolution.{r["ns"]}

/-- Upward binary64 literals of `2^{r["k"]}·K` and `2^{r["k"]}·K·κ/330`. -/
def literals : List String := [
    {lits}]

/-- The scale `2^-{r["k"]}`, as printed in the C file. -/
def scaleLiteral : String := "{r["scale"]}"

/-- The anchor term's literal. -/
def anchorLiteral : String := "{r["alit"]}"

/-- Exact binary64 values (what `PVCore.decode` returns), for the kernel route. -/
def xsQ : List ℚ := [{", ".join(T.lean_rat(x) for x in r["xs"])}]
def anchorQ : ℚ := {T.lean_rat(r["anchor"])}

end Table4Evolution.{r["ns"]}
"""


def main(argv: list[str]) -> int:
    check = "--check" in argv
    bad = 0
    for cfg in CONFIGS:
        r = build(cfg)
        cpath = PROJECT / "c" / f"{r['name']}.c"
        lpath = PROJECT / "Table4Evolution" / "Data" / f"{r['ns']}.lean"
        ltext = lean_data(r)
        if check:
            same = cpath.read_text() == r["csrc"] and lpath.read_text() == ltext
            bad += not same
            print(f"{r['name']}: {'same' if same else 'DIFFERS'}")
            continue
        cpath.write_text(r["csrc"])
        lpath.write_text(ltext)
        print(f"{r['name']}: K={float(r['K']):.9g} k={r['k']} exact coefficient {float(r['exact']):.10e}, "
              f"program ~ {float(r['estimate']):.10e}, anchor {float(r['anchor']):.4e}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
