#!/usr/bin/env python3
"""Deterministically prepare the exact accepted N17 Fap proof-library sources.
This is a byte/hash preparation gate, not proof acceptance or source-first PV.
"""
import argparse, hashlib, json, os, subprocess, sys
from pathlib import Path
HERE=Path(__file__).resolve().parent
R=HERE.parents[3]
S=R/'Solutions/RH080Next.v1'
def need(ok,message):
    if not ok:raise ValueError(message)
def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def load(path):return json.loads(path.read_text())
def verify(out,expected):
    need(out.is_dir()and not out.is_symlink(),'Prepared directory required')
    plan=load(out/'PLAN.json')
    for key in ['stages','n','namespace','seed','norm_numerator','total_abs','quad','input_sha256','producer_sha256']:
        need(plan[key]==expected[key],'Locked mathematical/producer identity mismatch:'+key)
    files=expected['lean_sources']+expected['payloads']
    need(len(expected['lean_sources'])==37 and len(expected['payloads'])==34,'Expected N17 proof-library dimensions')
    names=set()
    for row in files:
        name=row['file'];need(Path(name).name==name and name not in names,'Unsafe/duplicate file')
        names.add(name);p=out/name
        need(p.is_file()and not p.is_symlink(),'Missing regular payload:'+name)
        need(sha(p)==row['sha256']and p.stat().st_size==row['bytes'],'Generated bytes differ:'+name)
    need(all(p.is_file()and not p.is_symlink()and p.name in names|{'PLAN.json','PREPARED.json'}for p in out.iterdir()),'Unexpected prepared artifact')
    return files

def main():
    ap=argparse.ArgumentParser(allow_abbrev=False)
    ap.add_argument('--out',type=Path,default=S/'generated/fap17')
    ap.add_argument('--verify',action='store_true')
    a=ap.parse_args();expected_file=HERE/'FAP17_REGEN_EXPECTED.json';e=load(expected_file)
    producer=S/'dual/produce_fft_forest_certificate.py'
    source=R/'Solutions/RH080Study.v1/ablation/followup/independent-global-chord/inputs/witness-ap.json'
    need(sha(producer)==e['producer_sha256'],'Reviewed deterministic producer changed')
    need(sha(source)==e['input_sha256'],'Original fixed input changed')
    if a.verify:
        files=verify(a.out,e);receipt=load(a.out/'PREPARED.json')
        need(receipt['expected_sha256']==sha(expected_file)and receipt['controller_sha256']==sha(Path(__file__)),'Preparation receipt identity changed')
        print('PASS verified exact37 Lean sources and34 CSV inputs; proof compilation remains required')
        return
    need(not os.path.lexists(a.out),'Fresh output required; use --verify for an existing library')
    a.out.parent.mkdir(parents=True,exist_ok=True)
    command=[sys.executable,str(producer),'--stages','17','--out',str(a.out)]
    run=subprocess.run(command,capture_output=True,text=True)
    need(run.returncode==0,'Deterministic generator failed:'+run.stderr[-2000:])
    files=verify(a.out,e)
    record={'status':'PREPARED_EXACT_ACCEPTED_N17_DATA_NOT_PROOF_ACCEPTANCE','command':command,'controller_sha256':sha(Path(__file__)),
        'expected_sha256':sha(expected_file),'producer_sha256':sha(producer),'input_sha256':sha(source),
        'lean_sources':37,'csv_inputs':34,'generated_bytes':sum(row['bytes']for row in files),
        'numerical_status':'KERNEL_ONLY_NOT_SOURCE_FIRST_FFT_PV','proof_compilation_required':True}
    target=a.out/'PREPARED.json';need(not target.exists(),'Fresh preparation receipt required')
    temporary=target.with_name('.PREPARED.json.tmp')
    with temporary.open('x')as stream:json.dump(record,stream,indent=2,allow_nan=False);stream.write('\n');stream.flush();os.fsync(stream.fileno())
    try:os.link(temporary,target)
    finally:temporary.unlink()
    print(json.dumps({'status':record['status'],'lean_sources':37,'csv_inputs':34,'bytes':record['generated_bytes']}))
if __name__=='__main__':main()
