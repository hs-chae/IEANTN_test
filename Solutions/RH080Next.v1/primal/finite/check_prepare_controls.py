#!/usr/bin/env python3
"""Actual preparation-gate mutation controls in normal/-O/-OO Python.
Only experiment-owned, verified-regenerable fixture payloads are removed.
"""
import argparse,hashlib,json,os,subprocess,sys
from pathlib import Path
HERE=Path(__file__).resolve().parent
S=HERE.parents[1]
def need(v,m):
    if not v:raise ValueError(m)
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def main():
    ap=argparse.ArgumentParser(allow_abbrev=False);ap.add_argument('--prepared',type=Path,default=S/'generated/fap17');ap.add_argument('--run',type=Path,required=True);a=ap.parse_args()
    need(not os.path.lexists(a.run),'Fresh control directory required')
    checked=subprocess.run([sys.executable,str(HERE/'prepare_fap_library.py'),'--verify','--out',str(a.prepared)],capture_output=True,text=True)
    need(checked.returncode==0,'Preparation prerequisite failed:'+checked.stderr)
    a.run.mkdir(parents=True);rows=[]
    source=a.prepared.resolve(strict=True)
    for mode,args in [('normal',[]),('O',['-O']),('OO',['-OO'])]:
        for mutation in ['plan','payload','receipt']:
            directory=a.run/(mode+'-'+mutation);directory.mkdir();fixture=directory/'fixture';fixture.mkdir()
            identities={}
            for original in source.iterdir():
                need(original.is_file()and not original.is_symlink(),'Unexpected original artifact')
                target=fixture/original.name
                if original.name in('PLAN.json','PREPARED.json'):target.write_bytes(original.read_bytes())
                else:os.link(original,target)
                identities[target.name]=sha(target)
            if mutation=='plan':
                p=fixture/'PLAN.json';j=json.loads(p.read_text());j['norm_numerator']+=1;p.write_text(json.dumps(j))
            elif mutation=='receipt':
                p=fixture/'PREPARED.json';j=json.loads(p.read_text());j['controller_sha256']='0'*64;p.write_text(json.dumps(j))
            else:
                p=fixture/'ForestFinal.lean';data=p.read_bytes();p.unlink();p.write_bytes(data+b'\n-- unauthorized mutation\n')
            identities[p.name]=sha(p)
            command=[sys.executable,*args,str(HERE/'prepare_fap_library.py'),'--verify','--out',str(fixture)]
            result=subprocess.run(command,capture_output=True,text=True)
            (directory/'stdout').write_text(result.stdout);(directory/'stderr').write_text(result.stderr)
            reason={'plan':'Locked mathematical/producer identity mismatch','payload':'Generated bytes differ','receipt':'Preparation receipt identity changed'}[mutation]
            need(result.returncode!=0 and reason in result.stderr,'Mutation rejection route failed')
            # Inspect every owned cleanup target before unlinking; preserve the
            # original prepared data, failure logs, plan, receipt and identities.
            cleanup=[]
            for name,identity in identities.items():
                p=fixture/name
                need(p.is_file()and not p.is_symlink()and p.parent==fixture and sha(p)==identity,'Fixture changed before cleanup')
                if name not in('PLAN.json','PREPARED.json'):
                    cleanup.append(dict(file=name,sha256=identity,bytes=p.stat().st_size))
            (directory/'CLEANUP_TARGETS.json').write_text(json.dumps(cleanup,indent=2)+'\n')
            for row in cleanup:(fixture/row['file']).unlink()
            rows.append(dict(mode=mode,mutation=mutation,command=command,exitcode=result.returncode,expected_rejection=reason,removed_regenerable_files=len(cleanup),identity=identities))
    result={'status':'PASS_NINE_ACTUAL_CLI_MUTATION_CONTROLS_AND_VERIFIED_FIXTURE_CLEANUP','script_sha256':sha(Path(__file__)),'prepared_receipt_sha256':sha(source/'PREPARED.json'),'runs':rows}
    target=a.run/'RESULT.json';need(not target.exists(),'Fresh receipt required');target.write_text(json.dumps(result,indent=2)+'\n');print(result['status'])
if __name__=='__main__':main()
