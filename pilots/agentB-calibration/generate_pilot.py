"""Generate the pilot's program-A and program-B' instances. Every generated fact is re-checked in Lean.

Program B' instances come from the FROZEN generator `Solutions/RamanujanNumerics.v1/generate.py`,
imported as a library; its CLI (which writes the frozen baseline files) is never run.
Program A has its own small template below, built from the same `literal`/`upward` helpers.

usage: python generate_pilot.py old|new
"""
import hashlib, importlib.util, json, math, struct, sys
from fractions import Fraction as F
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
spec = importlib.util.spec_from_file_location(
    "frozen_generate", ROOT / "Solutions/RamanujanNumerics.v1/generate.py")
G = importlib.util.module_from_spec(spec)
spec.loader.exec_module(G)  # defines functions only; `if __name__=='__main__'` is not triggered

HEADER = """/-
Copyright (c) 2026 IEANTN contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Agent B (Claude), integration workstream (generated by generate_pilot.py)
-/
"""

SUM_PREFIX = """double sum(const double *a, unsigned n) {
    double s = 0.0;
    for (unsigned i = 0; i < n; ++i) {
        s += a[i];
    }
    return s;
}
"""

A_TEMPLATE = """IMPORTS
import CalibrationPilot.NamedSource

/-! Program A instance: the calibration deviation at `L₀ = 9400`, summed by the executed C
source `c/SOURCENAME`. Generated; the six `native_decide` facts below are its finite trust. -/

namespace NAMESPACE
open FKS2Scalar FKS2Table4 SumStability ForwardRamanujan CalibrationPilot
set_option maxRecDepth 100000
set_option maxHeartbeats 0

def targets : List ℚ := TARGETSREF
def literals : List String := [LITERALS]
def data : List ℚ := literals.map fun s => (loadLiteral s).getD 0
def entry : String := "ENTRY"
def program : ForwardRamanujan.Program := ⟨literals,"4096.0","0.0","0.0"⟩
def actualSource : String := include_str ".."/"c"/"SOURCENAME"
def initial : CState := FKS2SumBridge.sumInitial data
def sumOut : ℚ := (runSum data 0).getD 0
def outputBits : ℕ := OUTPUTBITS
def out : ℚ := decodeBits outputBits
def scale : ℚ := 4096
def fixedOffset : ℚ := 0
def positiveOffset : ℚ := 0
def r0 : ℚ := (round64 (sumOut*scale)).getD 0
def r1 : ℚ := (round64 (r0-fixedOffset)).getD 0
def suffixError : ℚ := 1/10^10
def totalError : ℚ := forwardError scale sumOut suffixError data.length
def bound : ℚ := BOUND

theorem source_check : sourceMatchesNamed actualSource entry program = true := by native_decide

theorem canon_check : (ForwardRamanujan.tokens (renderProgram program)).isSome = true := by
  native_decide

theorem enclosure_check : data.length=7 ∧ targets.length=7 ∧
    (∀ j ∈ Finset.range 7, targets[j]!/4096 ≤ data[j]!) ∧
    targets.sum ≤ scale*data.sum := by native_decide

theorem domain_check : ∀ r ∈ data,FKS2SumBridge.inputCheck r=true := by native_decide

theorem execution_check : program.inputs.mapM loadLiteral=some data ∧
    RepresentsInput initial data ∧ runSum data 0=some sumOut ∧
    chainCheck data 0 sumOut=true ∧ suffix program sumOut=some out ∧
    finiteBits outputBits=true ∧ encodePositiveNormal out=some outputBits := by
  unfold RepresentsInput
  native_decide

theorem suffix_check : loadLiteral program.scale=some scale ∧
    loadLiteral program.fixedOffset=some fixedOffset ∧
    loadLiteral program.positiveOffset=some positiveOffset ∧
    additionCheck (sumOut*scale) r0=true ∧
    additionCheck (r0-fixedOffset) r1=true ∧
    additionCheck (r1-positiveOffset) out=true ∧
    r0=scale*sumOut ∧
    |r1-(r0-fixedOffset)|≤1/10^11 ∧
    |out-(r1-positiveOffset)|≤1/10^11 := by native_decide

theorem budget_check : (data.map abs).sum=data.sum ∧
    0≤gamma (data.length-1) ∧ gamma (data.length-1)<1 ∧
    0≤scale ∧ 0≤totalError ∧ totalError≤1/10^8 ∧
    out+totalError≤bound := by native_decide

theorem suffix_roundoff : |out-(scale*sumOut-fixedOffset-positiveOffset)|≤suffixError := by
  have h1 := abs_le.mp suffix_check.2.2.2.2.2.2.2.1
  have h2 := abs_le.mp suffix_check.2.2.2.2.2.2.2.2
  rw [suffix_check.2.2.2.2.2.2.1] at h1
  rw [abs_le]
  unfold suffixError
  constructor <;> linarith

theorem suffix_IEEE : ForwardRamanujan.SuffixIEEE program sumOut out := by
  exact ⟨scale,fixedOffset,positiveOffset,r0,r1,
    suffix_check.1,suffix_check.2.1,suffix_check.2.2.1,
    additionCheck_sound suffix_check.2.2.2.1,
    additionCheck_sound suffix_check.2.2.2.2.1,
    additionCheck_sound suffix_check.2.2.2.2.2.1⟩

theorem concrete_execution : ExecNamed actualSource entry program initial out := by
  obtain ⟨final,hkernel⟩ := ForwardRamanujan.kernel_from_chain execution_check.2.2.2.1
    (show data.length≤64 by rw [enclosure_check.1];norm_num)
  exact ⟨source_check,by decide,by decide,data,sumOut,final,execution_check.1,
    execution_check.2.1,execution_check.2.2.1,hkernel,execution_check.2.2.2.2.1,suffix_IEEE⟩

/-- The frozen generic soundness theorem, applied through the named-source bridge. -/
theorem verified_with_domain (hd : ValidInputs data) {q : ℚ}
    (he : ExecNamed actualSource entry program initial q) :
    (targets.sum:ℝ)-(fixedOffset:ℝ)-(positiveOffset:ℝ)≤(q:ℝ)+(totalError:ℝ) := by
  have hn : 1≤data.length ∧ data.length≤64 := by rw [enclosure_check.1];norm_num
  have hg : (gamma (data.length-1):ℝ)<1 := by exact_mod_cast budget_check.2.2.1
  have href : (targets.sum:ℝ)≤(scale:ℝ)*(data.sum:ℝ) := by
    exact_mod_cast enclosure_check.2.2.2
  have hf : |(out:ℝ)-((scale:ℝ)*(sumOut:ℝ)-(fixedOffset:ℝ)-(positiveOffset:ℝ))|≤(suffixError:ℝ) := by
    exact_mod_cast suffix_roundoff
  exact source_linked_upper (to_exec he canon_check) execution_check.1 execution_check.2.2.1
    execution_check.2.2.2.2.1 hn hd budget_check.1 hg budget_check.2.2.2.1 href hf

theorem checked_domain : ValidInputs data := by
  intro r hr
  exact FKS2SumBridge.inputCheck_sound (domain_check r hr)

/-- What program A certifies: the sum of its targets is at most `bound`. -/
theorem certified_sum : (targets.sum:ℝ) ≤ (bound:ℝ) := by
  have h := verified_with_domain checked_domain concrete_execution
  have hb : (out:ℝ)+(totalError:ℝ)≤(bound:ℝ) := by
    exact_mod_cast budget_check.2.2.2.2.2.2
  have h0 : (fixedOffset:ℝ) = 0 := by norm_num [fixedOffset]
  have h1 : (positiveOffset:ℝ) = 0 := by norm_num [positiveOffset]
  rw [h0, h1] at h
  linarith
end NAMESPACE
"""


def create_A(module, namespace, targets, targets_ref, imports, label, entry, bound=None):
    """Program A: sum seven upward-rounded binary64 inputs (target/4096, floored at 2^-40), *4096."""
    vals = [G.upward(max(t / F(4096), F(1, 2 ** 40))) for t in targets]
    if any(not F(1, 2 ** 40) <= v <= 1 for v in vals):
        raise ValueError("unsupported input range")
    literals = list(map(G.literal, vals))
    s = 0.0
    for v in map(float, vals):
        s = s + v
    out = (s * 4096.0 - 0.0) - 0.0
    bits = struct.unpack(">Q", struct.pack(">d", out))[0]
    if bound is None:  # smallest 4-decimal number above out + 1e-8 (Lean re-checks out+err <= bound)
        bound = F(math.ceil((F(out) + F(1, 10 ** 8)) * 10 ** 4), 10 ** 4)
    src = (SUM_PREFIX + "\nstatic const double inputs[7] = {\n    " + ",\n    ".join(literals) +
           "\n};\ndouble " + entry + "(void) {\n    double s = sum(inputs, 7);\n"
           "    double r = (s * 4096.0);\n    r = (r - 0.0);\n    r = (r - 0.0);\n    return r;\n}\n")
    cpath = HERE / "c" / (label + ".c")
    cpath.write_text(src)
    lean = HEADER + A_TEMPLATE
    targets_lit = "[" + ",".join(G.rat(t) for t in targets) + "]"
    for k, v in {"IMPORTS": "", "NAMESPACE": namespace, "TARGETSREF": targets_lit,
                 "LITERALS": ",".join(json.dumps(x) for x in literals), "ENTRY": entry,
                 "SOURCENAME": label + ".c", "OUTPUTBITS": hex(bits), "BOUND": G.rat(bound)}.items():
        lean = lean.replace(k, v)
    dest = HERE / Path(*module.split(".")).with_suffix(".lean")
    dest.write_text(lean)
    return {"program": "A", "module": module, "entry": entry, "targets": [str(t) for t in targets],
            "literals": literals, "output_bits": format(bits, "016x"), "output_diagnostic": repr(out),
            "bound": str(bound), "source_sha256": hashlib.sha256(cpath.read_bytes()).hexdigest(),
            "lean_sha256": hashlib.sha256(dest.read_bytes()).hexdigest()}


def _scaled_create():
    """The frozen `create`, with its hard-coded scale 4096 turned into a parameter.

    Built by a mechanical, checked text substitution on the frozen source (8 sites). At scale 4096
    it must reproduce the frozen generator byte for byte; `fidelity_check` verifies that.
    """
    src = (ROOT / "Solutions/RamanujanNumerics.v1/generate.py").read_text()
    body = src[src.index("def create("):src.index("if __name__=='__main__':")]
    subs = [("def create(", "def create_scaled(SCALE_INT,"),
            ("v/F(4096)", "v/F(SCALE_INT)"),
            ("s*4096.0", "s*float(SCALE_INT)"),
            ("(s * 4096.0);", "(s * '+str(SCALE_INT)+'.0);"),
            ('⟨literals,"4096.0"', '⟨literals,"SCALELIT"'),
            ("def scale : ℚ := 4096", "def scale : ℚ := SCALEINT"),
            ("[j]!/4096", "[j]!/SCALEINT"),
            ("g/F(4096)", "g/F(SCALE_INT)"),
            ("replacements={", "replacements={'SCALELIT':str(SCALE_INT)+'.0','SCALEINT':str(SCALE_INT),")]
    for a, b in subs:
        if a not in body:
            raise RuntimeError("frozen generator changed: " + a)
        body = body.replace(a, b)
    if "4096" in body:
        raise RuntimeError("unconverted scale site remains")
    ns = dict(vars(G))
    exec(compile(body, "generate.py[create_scaled]", "exec"), ns)
    return ns["create_scaled"]


create_scaled = _scaled_create()


def create_B(module, m, M, label, scale):
    """Program B' (frozen template, scale parameter) at A = 9400, Y = 9401; bound = next 4-decimal."""
    rec = create_scaled(scale, HERE, module, module, m, M, A=9400, Y=9401, n=7, bound=F(10 ** 6),
                        label=label)
    out = F(float(rec["output_diagnostic"]))
    bound = F(math.ceil((out + F(1, 10 ** 8)) * 10 ** 4), 10 ** 4)
    rec = create_scaled(scale, HERE, module, module, m, M, A=9400, Y=9401, n=7, bound=bound,
                        label=label)
    rec["program"] = "B'"
    rec["scale"] = scale
    return rec


def fidelity_check(tmp):
    """At scale 4096 the parameterized copy must equal the frozen generator byte for byte."""
    tmp = Path(tmp)
    for q in (tmp / "frozen", tmp / "scaled"):
        (q / "c").mkdir(parents=True, exist_ok=True)
    args = dict(A=3914, Y=3915, n=7, bound=F("9.101"), label="probe")
    r1 = G.create(tmp / "frozen", "X.Probe", "X.Probe", 119, 131, **args)
    r2 = create_scaled(4096, tmp / "scaled", "X.Probe", "X.Probe", 119, 131, **args)
    same = (r1["source_sha256"] == r2["source_sha256"] and r1["lean_sha256"] == r2["lean_sha256"])
    upd = hashlib.sha256((ROOT / "Solutions/RamanujanNumerics.v2/c/updated.c").read_bytes()).hexdigest()
    return {"frozen_vs_scaled_identical": same, "probe_c_sha256": r1["source_sha256"],
            "matches_published_updated_c": r1["source_sha256"] == upd}


def main(which):
    (HERE / "c").mkdir(exist_ok=True)
    if which == "old":
        t = [F(3110), F(1, 5000), F(3600) / (F(99, 100) ** 7 * 9400), F(720, 9400), F(1, 10 ** 12),
             F(720 * 7 * 256) / F(9400) ** 2, F(1, 10 ** 12)]
        a = create_A("CalibrationPilot.OldA", "CalibrationPilot.OldA", t,
                     "CalibrationPilot.OldInput.targets", "import CalibrationPilot.OldInput",
                     "calibration_old", "calibration_deviation")
        delta = F(a["bound"])
        # 2M = 6461 > 4096: the frozen family's input range (<= 1 after scaling) needs scale 8192.
        b = create_B("CalibrationPilot.OldB", F(120) - delta, F(120) + delta, "ramanujan_9401_old",
                     8192)
    elif which == "fidelity":
        import tempfile
        with tempfile.TemporaryDirectory() as d:
            r = fidelity_check(d)
        (HERE / "generated_fidelity.json").write_text(json.dumps(r, indent=1) + "\n")
        print(r)
        return
    elif which == "new":
        t = [F(1, 10 ** 12), F(1, 5000), F(1, 10 ** 12) / (F(99, 100) ** 7 * 9400), F(720, 9400),
             F(1, 10 ** 12), F(720 * 7 * 256) / F(9400) ** 2, F(1, 10 ** 12)]
        a = create_A("CalibrationPilot.NewA", "CalibrationPilot.NewA", t,
                     "CalibrationPilot.NewInput.targets", "import CalibrationPilot.NewInput",
                     "calibration_new", "calibration_deviation")
        delta = F(a["bound"])
        # m = 120 - delta > 0: the frozen program shape needs a positive output, so B' is
        # instantiated at m = 0 and `epsilon_shift_nonneg` subtracts m in exact arithmetic.
        b = create_B("CalibrationPilot.NewB", F(0), F(120) + delta, "ramanujan_9401_new", 4096)
    else:
        raise SystemExit(__doc__)
    rec = {"A": a, "B": b, "delta": str(delta)}
    (HERE / f"generated_{which}.json").write_text(json.dumps(rec, indent=1) + "\n")
    print(which, "delta =", delta, "=", float(delta), "| B' bound =", b["bound"], "| A bits", a["output_bits"],
          "| B' bits", b["output_bits"])


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "")
